"""The map → the programs' data and the intents' words (the pattern 'A room is data').

    python world/gen_map.py            write domains/shared/home_map.llp and each package's intent handles
    python world/gen_map.py --check    exit 1 when a written file differs from what the map gives (CI)

The rules name roles only (r1, l1, u1, t1, ir1); this writes the role types, the static facts
that place them (light_in, unit_in, has_unit / no_unit), and, in each package's intent.yaml, the
block after the `# --- handles` marker: the words a person may use for each role.

A device named without its room (the map's `unnamed`: "the light", "the heating"): where the home
has more than one of the kind, its words bind the kind's unnamed handle (la, ua), and this writes
the package's which.llp, one rule per command of that kind refusing it with a reason that names the
rooms which have one (the conversation then asks which room; the rules never pick one). Where the
home has one of the kind, the words are that device's own."""
import json
import re
import sys
from pathlib import Path

HOME = Path(__file__).resolve().parent.parent
MAP = HOME / "world" / "home.map.json"
MARK = "# --- handles (generated by world/gen_map.py from world/home.map.json: do not edit below) ---"
STANDING = {"light": "lx", "unit": "ux", "tv": "tx", "irdev": "irx", "room": "rx"}
INTENT_HANDLES = {            # package -> [(handle kind, map section)]
    "lights": [("light", "lights"), ("room", "rooms")],
    "air": [("unit", "units")],
    "media": [("tv", "tvs"), ("irdev", "ir")],
    "comfort": [("room", "rooms")],
}


KIND_OF = {"lights": "light", "units": "unit", "tvs": "tv", "ir": "irdev", "rooms": "room"}
SECTION_OF = {kind: section for section, kind in KIND_OF.items()}
ROW = re.compile(r"^(\w+)\(\{\w+:(\w+)\}\)$")      # a map row's atom: cmd_light_on({device:light})


def load(path=MAP):
    return json.loads(Path(path).read_text())


def roles(m, section):
    return [k for k in m[section] if not k.startswith("_")]


def unnamed(m, section):
    """The section's unnamed entry ({handle, noun, words}), or None."""
    return (m.get("unnamed") or {}).get(section)


def ambiguous(m, section):
    """The section's unnamed entry when the home has more than one device of it, else None."""
    u = unnamed(m, section)
    return u if u and len(roles(m, section)) > 1 else None


def device_type(m, section):
    handles = roles(m, section) + [STANDING[KIND_OF[section]]]
    if unnamed(m, section):
        handles.append(unnamed(m, section)["handle"])
    return "type %s {%s}." % (KIND_OF[section], " ".join(handles))


def map_llp(m):
    rooms = roles(m, "rooms")
    with_unit = sorted({m["units"][u]["room"] for u in roles(m, "units")})
    out = ["% generated by world/gen_map.py from world/home.map.json: do not edit",
           "catalog home_map 1.",
           "% the role types and where each role is; the names behind the roles are the map's.",
           "type room {%s rx}." % " ".join(rooms),
           "% each device type ends with its standing handle (lx, ux, tx, irx): a device the person named",
           "% that the home does not have; the rules refuse it, the host never actuates it",
           "% and, where the map names one, its unnamed handle (la, ua): the device named without its room",
           device_type(m, "lights"),
           device_type(m, "units"),
           device_type(m, "tvs"),
           device_type(m, "ir"),
           "",
           "bwd light_in(light, room).",
           "bwd unit_in(unit, room).",
           "bwd has_unit(room).",
           "bwd no_unit(room).",
           ""]
    out += ["light_in(%s, %s)." % (l, m["lights"][l]["room"]) for l in roles(m, "lights")]
    out += ["unit_in(%s, %s)." % (u, m["units"][u]["room"]) for u in roles(m, "units")]
    out += ["has_unit(%s)." % r for r in rooms if r in with_unit]
    out += ["no_unit(%s)." % r for r in rooms if r not in with_unit]
    return "\n".join(out) + "\n"


def handles_block(m, pkg):
    lines = [MARK, "handles:"]
    standing = []
    for kind, section in INTENT_HANDLES[pkg]:
        lines.append("  %s:" % kind)
        rs, u = roles(m, section), unnamed(m, section)
        for role in rs:
            words = m[section][role]["words"] + (u["words"] if u and len(rs) == 1 else [])
            lines.append("    %s: {description: [%s]}" % (role, ", ".join(json.dumps(w) for w in words)))
        standing.append(STANDING[kind])
        if ambiguous(m, section):
            lines.append("    %s: {description: [%s]}" % (u["handle"], ", ".join(json.dumps(w) for w in u["words"])))
            standing.append(u["handle"])
    kinds = [k for k, _ in INTENT_HANDLES[pkg]]
    lines.append("fallback: {%s}" % ", ".join("%s: %s" % (k, STANDING[k]) for k in kinds))
    lines.append("standing: [%s]" % ", ".join(standing))
    return "\n".join(lines) + "\n"


def said(items):
    """['the bedroom', 'the lab', 'the kitchen'] -> 'the bedroom, the lab and the kitchen'."""
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def map_rows(head):
    """An intent.yaml head's map rows -> [(command pred, device kind, act)]."""
    import yaml
    rows = []
    for r in (yaml.safe_load(head) or {}).get("map") or []:
        f = ROW.match(r.get("atom", ""))
        if f:
            rows.append((f.group(1), f.group(2), r["act"]))
    return rows


def which_llp(m, pkg, rows):
    """A package's which.llp: for each command row whose device is a kind the home has more than one
    of, the rule refusing the kind's unnamed handle with the rooms that have one; None when no row is."""
    out = ["% generated by world/gen_map.py from world/home.map.json and the package's intent.yaml map: do not edit",
           "% A device named without its room where the home has more than one: refused, the reason naming",
           "% the rooms that have one, so the conversation asks which room. The rules never pick one.",
           "catalog %s_which 1." % pkg,
           "stage serve {"]
    n = 0
    for pred, kind, act in rows:
        section = SECTION_OF.get(kind, "")
        u = ambiguous(m, section)
        if not u:
            continue
        rooms = list(dict.fromkeys(m["rooms"][m[section][r]["room"]]["name"] for r in roles(m, section)))
        name = "which_" + (pred[len("cmd_"):] if pred.startswith("cmd_") else pred)
        out += ["  %%%% I can't tell which %s you mean: there is one in %s. Which room?"
                % (u["noun"], said(["the " + r for r in rooms])),
                "  %s [dyn] : %s(%s) -o refused(%s)." % (name, pred, u["handle"], act)]
        n += 1
    out.append("}")
    return "\n".join(out) + "\n" if n else None


def targets(m):
    out = {HOME / "domains" / "shared" / "home_map.llp": map_llp(m)}
    for pkg in INTENT_HANDLES:
        p = HOME / "domains" / pkg / "intent.yaml"
        head = p.read_text().split(MARK)[0] if p.exists() else ""
        out[p] = head.rstrip("\n") + "\n\n" + handles_block(m, pkg)
        which = which_llp(m, pkg, map_rows(head))
        if which:
            out[HOME / "domains" / pkg / "which.llp"] = which
    return out


def main(argv):
    m = load()
    stale = []
    for path, text in targets(m).items():
        if path.exists() and path.read_text() == text:
            continue
        if "--check" in argv:
            stale.append(str(path.relative_to(HOME)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(HOME))
    if stale:
        print("stale (run world/gen_map.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
