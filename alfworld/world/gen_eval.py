"""gen_eval.py — the task's instrument cases (spec16 s-b12d90f2 step 3, part 2; metis-lang spec/16): the fetch's
failure risk within a horizon, as a level the task reads.

domains/hier/task/eval/ holds the world model (world.llp: the task as installed, today's go_for @w look; world_level.llp:
the certified form, its decision on a belief level with static weights; world_rules.llp: the world, shared) and the
manifests (fetch[_level][_lone].yaml: the form, and a lone belief). This tool writes what is derived:
  task_level_domain.llp, task_level.llp   the task with go_for replaced by the level rules (refused if go_for moved)
  cases/<belief>[_level].yaml              one case per belief shape and form: the init (the fetch, the support, and
                                            in the level form the host's place_level atoms) and every port tuple bound
`python3 world/gen_eval.py [--check]` from alfworld/: --check exits 1 when a file is not as written here.

The beliefs are the map's, over the roles (the capacity's p1..p3 the places likeliest to hold the target): PEAKED
(one place ≥ 0.7), SPREAD (none), and LOST (a lone belief, some mass on no candidate: the target is nowhere the map
looked). The task's choice weight (look) and the truth's distribution (where) carry the same numbers: one port, two
roles (spec/16 §3), the honest form's truth a separate pred (truly) the decision never reads."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HIER = os.path.join(os.path.dirname(HERE), "domains", "hier")
EVAL = os.path.join(HIER, "task", "eval")

OBJECTS = ("target", "other")
RECEPTACLES = ("dest", "p0", "p1", "p2", "p3", "p4", "p5", "p6", "p7", "p8")
BELIEFS = {                                     # name: ({place: P(target there)}, lone)
    "peaked": ({"p1": 0.8, "p2": 0.15, "p3": 0.05}, False),
    "spread": ({"p1": 0.4, "p2": 0.35, "p3": 0.25}, False),
    "lost": ({"p1": 0.5, "p2": 0.3}, True),     # 0.2 on no candidate
}
LEVEL_AT, LEVEL_NAMES = (0.3, 0.7), ("unlikely", "maybe", "sure")   # belief-levels' thresholds (step 1, the brief)
GO_FOR = "  go_for [dyn] : want(O) * start * $inrecep(O, R) -o want(O) * goto(R)  @w look(O, R)."
GO_LEVEL = [
    "  %% {O} is surely in {R}: I go there.",
    "  go_sure [dyn] : want(O) * start * $inrecep(O, R) * $place_level(sure, O, R) -o want(O) * goto(R).",
    "  %% {O} may be in {R}: I go there.",
    "  go_maybe [dyn] : want(O) * start * $inrecep(O, R) * $place_level(maybe, O, R) -o want(O) * goto(R).",
    "  %% {O} is unlikely in {R}: I go there, a tenth as readily.",
    "  go_unlikely [dyn] : want(O) * start * $inrecep(O, R) * $place_level(unlikely, O, R) -o want(O) * goto(R)  @w 0.1.",
]


def level_of(p):
    return LEVEL_NAMES[sum(1 for t in LEVEL_AT if t <= p)]


def task_level_domain():
    """../../task_domain.llp with go_for replaced by the level rules, its includes re-rooted from eval/."""
    src = open(os.path.join(HIER, "task_domain.llp")).read()
    lines = src.split("\n")
    if lines.count(GO_FOR) != 1:
        raise SystemExit("gen_eval: task_domain.llp's go_for is not the one this tool replaces:\n" + GO_FOR)
    i = lines.index(GO_FOR)
    lines = lines[:i - 1] + GO_LEVEL + lines[i + 1:]          # its %% doc line goes with it
    out = "\n".join(lines).replace('include "iface/alfworld.llp".', 'include "../../iface/alfworld.llp".')
    out = out.replace("catalog task_domain 1.", "catalog task_level_domain 1.")
    out = out.replace("weight look(O, R) reads {inrecep(O, R)}.",
                      "weight look(O, R) reads {inrecep(O, R)}.\n"
                      "type certainty {%s}.\n"
                      "pred place_level(certainty, object, receptacle) : task.   %% the host's: the where belief's level "
                      "(the manifest's levels: place_level)" % " ".join(LEVEL_NAMES))
    head = ("% GENERATED by world/gen_eval.py from ../../task_domain.llp (spec16 s-b12d90f2 step 3): the task with its\n"
            "% go_for decided on a belief LEVEL with static weights (spec/16 §8's certified form), for the instrument only.\n")
    return head + out


def task_level():
    src = open(os.path.join(HIER, "task", "task.llp")).read()
    out = src.replace('include "../task_domain.llp".', 'include "task_level_domain.llp".') \
             .replace('include "../capacity.llp".', 'include "../../capacity.llp".') \
             .replace("catalog task 1.", "catalog task_level 1.")
    return "% GENERATED by world/gen_eval.py from ../task.llp: the level form's instance.\n" + \
        "\n".join(l for l in out.split("\n") if not l.startswith("#"))


def table(port, values):
    rows = ["  %s:" % port]
    for o in OBJECTS:
        for r in RECEPTACLES:
            rows.append("    %s(%s, %s): %s" % (port, o, r, repr(values.get((o, r), 0))))
    return rows


def case(name, level):
    bel, lone = BELIEFS[name]
    values = {("target", r): p for r, p in bel.items()}
    values[("other", "p0")] = 1                                  # the other object: in p0, surely (a group of its own)
    init = ["fetch(target, dest)"] + ["inrecep(target, %s)" % r for r in sorted(bel)]
    if level:
        init += ["place_level(%s, target, %s)" % (level_of(p), r) for r, p in sorted(bel.items())]
    manifest = "fetch%s%s.yaml" % ("_level" if level else "", "_lone" if lone else "")
    form = "the decision on place_level, static weights" if level else "today's go_for @w look"
    rows = ["# GENERATED by world/gen_eval.py: the %s belief (%s), %s" % (
                name, ", ".join("%s %s" % (r, p) for r, p in sorted(bel.items())) + (", the rest on no candidate" if lone else ""), form),
            "manifest: ../%s" % manifest,
            "init: [%s]" % ", ".join(init),
            "ports:"] + table("look", values) + table("where", values)
    return "\n".join(rows) + "\n"


def files():
    out = {os.path.join(EVAL, "task_level_domain.llp"): task_level_domain(),
           os.path.join(EVAL, "task_level.llp"): task_level()}
    for name in BELIEFS:
        out[os.path.join(EVAL, "cases", "%s.yaml" % name)] = case(name, False)
        out[os.path.join(EVAL, "cases", "%s_level.yaml" % name)] = case(name, True)
    return out


def main(argv):
    check = "--check" in argv
    stale = []
    for path, text in files().items():
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(os.path.relpath(path))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
    if stale:
        print("gen_eval: not as written here (run without --check): %s" % ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
