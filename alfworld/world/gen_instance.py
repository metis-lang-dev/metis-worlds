"""gen_instance.py — a game as a generated instance over the lifted domain (world-alfworld
step 1): `python -m world.gen_instance GAME_DIR [--out DIR]` writes `<id>.llp` (the game's
types, its static facts as Horn facts, its task, its start) and `<id>.handles.json` (the
handle map the host needs to name things in commands). Runs under the world's venv.
"""
import argparse, json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from alf_gym import Game  # noqa: E402
from ground import PAIRS  # noqa: E402

def _pick_and_place(p, info):
    """target(O) for the pickupable objects of the target type; dest(R) for the receptacles of
    the parent type — the task resolved to the game's things, so the rules carry no type."""
    ot, rt = p["object_target"].lower() + "_t", p["parent_target"].lower() + "_t"
    st = set(info["static"])
    objs = sorted(a[len("otype("):-1].split(",")[0] for a in st if a.startswith("otype(") and a.endswith("," + ot + ")"))
    objs = [o for o in objs if "pickupable(%s)" % o in st]
    recs = sorted(a[len("rtype("):-1].split(",")[0] for a in st if a.startswith("rtype(") and a.endswith("," + rt + ")"))
    return ["target(%s)." % o for o in objs] + ["dest(%s)." % r for r in recs]


TASK_FACTS = {
    # task_type -> the task's facts from pddl_params and the game's static facts (the first family only, for now)
    "pick_and_place_simple": _pick_and_place,
}


def instance_id(game_dir):
    parts = os.path.normpath(game_dir).split(os.sep)
    return (parts[-2] + "__" + parts[-1]).lower().replace("-", "_").replace(".", "_")


def generate(game_dir, out_dir, domain_rel="../alfred_domain.llp"):
    g = Game()
    info = g.open(os.path.join(game_dir, "game.tw-pddl"))
    h = info["handles"]
    kinds = {}
    for handle, kind in h["kind"].items():
        kinds.setdefault(kind, []).append(handle)
    task = info["task_type"]
    if task not in TASK_FACTS:
        raise SystemExit("task type %r is not in the first family yet" % task)
    iid = instance_id(game_dir)
    lines = ["% " + iid + " — ALFWorld game " + os.path.relpath(game_dir, os.environ.get("ALFWORLD_DATA", "/")) + ", generated by world/gen_instance.py: the game's types,",
             "% its static facts, its task (" + task + ": " + json.dumps(info["params"]) + ") and its start over the lifted alfred_domain.llp.",
             "% " + (info.get("desc") or ""),
             "catalog " + iid + " 1.",
             'provenance text "generated from ALFWorld game %s" "2026-10-21".' % os.path.basename(os.path.dirname(game_dir)),
             'include "%s".' % domain_rel]
    for kind in ("location", "receptacle", "object", "otype", "rtype"):
        lines.append("type %s {%s}." % (kind, " ".join(sorted(kinds.get(kind, []))) or "none"))
    lines.append("")
    lines.append("% the static facts")
    for a in info["static"]:
        lines.append(a + ".")
    # the complements the rules need
    receptacles = sorted(kinds.get("receptacle", []))
    openable = {a[len("openable("):-1] for a in info["static"] if a.startswith("openable(")}
    for r in receptacles:
        if r not in openable:
            lines.append("notopenable(%s)." % r)
    lines.append("")
    lines.append("% the task")
    lines += TASK_FACTS[task](info["params"], info)
    lines.append("")
    lines.append("% the start: the game's dynamic facts, and the policy's own tokens")
    dyn = info["init"]
    for a in dyn:
        lines.append("#init %s 1" % a)
    opened = {a[len("opened("):-1] for a in dyn if a.startswith("opened(")}
    for r in sorted(openable):
        if r not in opened:
            lines.append("#init closed(%s) 1" % r)
    if not any(a == "holding" for a in dyn):
        lines.append("#init handsfree 1")
    lines.append("#init unchosen 1")
    lines.append("#steps 40")
    lines.append("#seeds 1")
    lines.append("#query placed")
    # one PACKAGE per game: domains/<iid>/{<iid>.llp, domain.yaml, game.json, alf_host.py}
    pkg = os.path.join(out_dir, iid)
    os.makedirs(pkg, exist_ok=True)
    path = os.path.join(pkg, iid + ".llp")
    open(path, "w").write("\n".join(lines) + "\n")
    json.dump({"game": os.path.join(game_dir, "game.tw-pddl"), "task_type": task, "params": info["params"],
               "handles": h}, open(os.path.join(pkg, "game.json"), "w"), indent=1)
    open(os.path.join(pkg, "domain.yaml"), "w").write(
        "# %s — an ALFWorld game as a package (generated by world/gen_instance.py): the program is the\n"
        "# instance over ../alfred_domain.llp; the host is the world's (alf_host.py, a shim).\n"
        "program: %s.llp\nhost: alf_host.py:make\nclock: {beats: 1}\nrecords: records/\n"
        "display: ALFWorld %s\nline: \"%s\"\nvoice: own\n" % (iid, iid, task, (info.get("desc") or task).replace('"', "'").strip()))
    shim = open(os.path.join(HERE, "package_host.py")).read().replace("__WORLD__", HERE)
    open(os.path.join(pkg, "alf_host.py"), "w").write(shim)
    return path, len(dyn), len(info["static"])


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("game_dir")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    g = json.load(open(os.path.join(a.game_dir, "traj_data.json")))
    out = a.out or os.path.join(HERE, "..", "domains")
    path, nd, ns = generate(a.game_dir, out)
    print("%s: %d dynamic, %d static" % (path, nd, ns))
    return 0


if __name__ == "__main__":
    sys.exit(main())
